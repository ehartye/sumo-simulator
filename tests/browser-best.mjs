import { chromium } from '../../agent-meshes/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';

const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1500, height: 1100 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const selection = loop => ({ revision: `revision-${loop}`, loop, champion: { name: `champion_${loop}`, source: `# champion ${loop}\npass` }, opponent: { name: 'opponent', source: '# opponent\npass' }, score: { wins: 3, draws: 3, losses: 0 }, replayUrl: '/trials/fixture.json' });
let current = selection(3), replay;
await page.addInitScript(() => { const timeout = window.setTimeout; window.setTimeout = (fn, delay, ...args) => timeout(fn, delay === 10000 ? 200 : delay, ...args); });
await page.route('**/api/strategy-selection', route => route.fulfill({ json: current }));
await page.route('**/trials/fixture.json', route => route.fulfill({ json: replay }));
try {
  await page.goto('http://127.0.0.1:8765');
  await page.waitForFunction(() => !document.querySelector('#loading'));
  assert.equal(await page.locator('#load-best').count(), 1, 'Best strategy control exists');
  assert.equal(await page.locator('#code0').inputValue(), current.champion.source, 'Boot selects current champion');
  assert.equal(await page.locator('#preset0').inputValue(), current.champion.name);
  replay = await page.evaluate(() => fetch('/api/replay').then(response => response.json()));
  current = selection(4);
  await page.waitForFunction(() => document.querySelector('#code0').value === '# champion 4\npass');
  await page.locator('#code0').fill('# user experiment\npass');
  current = selection(5);
  await page.waitForFunction(() => document.querySelector('#best-label').textContent.includes('champion 5'));
  assert.equal(await page.locator('#code0').inputValue(), '# user experiment\npass', 'Poll preserves edits');
  assert.match(await page.locator('#best-label').textContent(), /available/i);
  await page.click('#load-best');
  await page.waitForFunction(() => document.querySelector('#code0').value === '# champion 5\npass');
  await page.click('#run');
  await page.waitForFunction(() => document.querySelector('#run').textContent.includes('Pause'));
  current = selection(6);
  await page.waitForFunction(() => document.querySelector('#best-label').textContent.includes('champion 6'));
  assert.equal(await page.locator('#code0').inputValue(), '# champion 5\npass', 'Poll preserves running match');
  await page.click('#run');
  await page.waitForFunction(() => document.querySelector('#code0').value === '# champion 6\npass');
  await page.click('#inspect-best');
  await page.waitForFunction(() => document.querySelector('#replay-source').textContent.includes('Loaded replay'));
  current = selection(7);
  await page.waitForFunction(() => document.querySelector('#best-label').textContent.includes('champion 7'));
  assert.equal(await page.locator('#code0').inputValue(), replay.metadata.programs[0], 'Poll preserves loaded replay');
  await page.click('#load-best');
  await page.waitForFunction(() => document.querySelector('#code0').value === '# champion 7\npass');
  await page.click('#step');
  await page.waitForFunction(() => document.querySelector('#clock').textContent === '0.05');
  const active = await page.evaluate(() => fetch('/api/replay').then(response => response.json()));
  assert.equal(active.metadata.programs[0], current.champion.source, 'Fresh backend uses latest choice');
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.setViewportSize({ width: 1500, height: 1100 });
  await page.screenshot({ path: 'artifacts/screenshots/latest-best.png', fullPage: true });
  current = null;
  await page.waitForFunction(() => document.querySelector('#load-best').disabled);
  assert.equal(await page.locator('#code0').inputValue(), '# champion 7\npass', 'No selection preserves editors');
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ latestBest: 'passed', checks: ['boot', 'auto update', 'edit guard', 'running guard', 'replay guard', 'manual load', 'winning replay', 'fresh backend', 'mobile', 'null selection'], errors }));
} finally { await browser.close(); }
